UPDATE module_privileges SET
  description_he = 'הוספת בוגרת ידנית, עריכת כל הפרטים שלה ומחיקתה מרשימת הבוגרות.',
  description_ru = 'Добавление выпускницы вручную, правка всех её данных и удаление из списка выпускниц.',
  description_en = 'Adds a graduate manually, edits all her details and removes her from the alumni list.'
WHERE module = 'alumni' AND privilege_code = 'manage';
