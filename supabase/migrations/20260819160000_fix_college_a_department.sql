-- ============================================================================
-- Маршрут מכללה (קבוצה א׳, 4 года, code='college_a') был засеян с ПЛЕЙСХОЛДЕРНЫМ
-- department_id ('a0000000-0000-4000-8000-000000000003', 20260818170000), которого
-- нет среди реальных подразделений владельца. Из-за этого фильтр study-tracks по
-- подразделению (scope='department' → department_id ∈ дерево пользователя) прятал
-- этот маршрут от менеджера колледжа: в форме создания מקצוע был виден только
-- 'college' (קבוצה ב׳, 3 года), а 'college_a' — нет.
--
-- Привязываем 'college_a' к ТОМУ ЖЕ подразделению, что и 'college' (реальное
-- подразделение колледжа менеджера) — без хардкода UUID. Тогда в форме появятся
-- оба маршрута: 3 года (גדולות) и 4 года (קטנות). Идемпотентно.
-- ============================================================================

UPDATE study_tracks
SET department_id = (SELECT department_id FROM study_tracks WHERE code = 'college'),
    is_active = true
WHERE code = 'college_a';
