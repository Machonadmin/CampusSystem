-- B11 (решение владельца 08.10.2026): источник лида «התקשרה בעצמה» (self)
-- и «שיחת טלפון» (call) объединены в ОДИН источник «טלפוני»
-- (en "Phone", ru «Телефон»).
--
-- Остаётся код 'self' — именно его предлагают формы создания лида
-- (EducationJourneyForm, QuickLeadModal). Код 'call' формы не предлагают;
-- старые записи с ним переводим в 'self', чтобы отчёт «по источнику»
-- показывал одну строку.
--
-- Идемпотентно: повторный запуск ничего не меняет.
-- ═════════════════════════════════════════════════════════════════════

UPDATE education_journeys
   SET referral_source = 'self'
 WHERE referral_source = 'call';
