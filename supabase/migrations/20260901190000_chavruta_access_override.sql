-- ============================================================================
-- Хеврута: персональный оверрайд доступа.
--
-- Доступ к хевруте до сих пор был ЧИСТО автоматическим: кодеш-преподаватель
-- (class_teachers групп кафедры кодеша) ∪ ручная таблица chavruta_teachers.
-- Выключить его для конкретного человека было НЕЛЬЗЯ — кейс владельца:
-- «אחראית יהדות» преподаёт в кодеше, но хеврута ей не положена.
--
-- Решение: effectiveChavrutaTeacherIds теперь читает person_privileges
-- (module='chavruta', privilege_code='access') — grant добавляет, deny убирает.
-- Здесь регистрируем привилегию в каталоге, чтобы она появилась в модалке
-- «הרשאות אישיות» (Настройки → משתמשים → הרשאות אישיות) как обычный переключатель.
--
-- Идемпотентно (ON CONFLICT).
-- ============================================================================

INSERT INTO module_privileges (module, privilege_code, privilege_name, sort_order)
VALUES ('chavruta', 'access', 'Доступ к хевруте (перекрывает автоправило кодеш-учителя)', 10)
ON CONFLICT (module, privilege_code) DO NOTHING;
