UPDATE departments SET
  name    = 'Старшие (университет, Туро, старший колледж)',
  name_he = 'גדולות (אוניברסיטה, טורו, מכללה גדולות)',
  name_en = 'Older (university, Touro, senior college)'
WHERE id = 'a0000000-0000-4000-8000-000000000002'
  AND name_he IN ('בוגרות (אוניברסיטה, טורו, מכללה גדולות)', 'קבוצה ב׳');

UPDATE departments SET
  name    = 'Колледж — старшие (с 11 класса)',
  name_he = 'מכללה — גדולות (מכיתה 11)',
  name_en = 'College — older (from grade 11)'
WHERE name_he IN ('מכללה — בוגרות (מכיתה 11)', 'מכללה · גדולות (בסיס כיתה 11, 3 שנים)');

UPDATE study_tracks SET
  name_he = 'מכללה — גדולות (מכיתה 11)',
  name_ru = 'Колледж — старшие (с 11 класса)',
  name_en = 'College — older (from grade 11)'
WHERE code = 'college_g11'
  AND name_he IN ('מכללה — בוגרות (מכיתה 11)', 'מכללה · גדולות');
