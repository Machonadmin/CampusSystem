-- ═════════════════════════════════════════════════════════════════════
-- Порядок прав в каталоге: пересчёт по правилу вместо исторической смеси.
--
-- ПОЧЕМУ ЭТО НЕ КОСМЕТИКА. При равном sort_order Postgres возвращает строки в
-- ПРОИЗВОЛЬНОМ порядке, и он может отличаться от запроса к запросу: на экране
-- два права молча меняются местами между загрузками. Для модуля, который
-- существует ради «навели порядок и стало понятно», это прямое противоречие
-- замыслу.
--
-- ─── Что обнаружилось ───────────────────────────────────────────────────────
--
-- Каталог 20260916120000 вставляет строки через INSERT ... ON CONFLICT DO
-- NOTHING, а значит его sort_order применяется ТОЛЬКО К НОВЫМ строкам. Уже
-- существовавшие сохранили старые значения из сида 002. В базе получилась
-- смесь двух нумераций, и в ней:
--
--   • в 13 модулях 'access' (новая строка, счётчик дал 1) встал ровно на место
--     'view' (старая строка, из 002 тоже 1);
--   • data_security.manage_tree (303 из каталога) и manage_units (303, задан
--     вручную в 20260917120000) столкнулись между собой.
--
-- Найдено самопроверкой миграции на базе владельца: 14 пар. На чистой БД
-- проблема не воспроизводится — поэтому её и не поймал статический тест по
-- текстам миграций: он моделирует «что написано», а не «что вставилось».
--
-- ─── Что делает эта миграция ────────────────────────────────────────────────
--
-- Не латает 14 пар, а убирает причину: пересчитывает sort_order ВСЕХ строк по
-- правилу, одинаковому для существующих и будущих прав —
--
--     access → 0      (вход в модуль, всегда первым)
--     view   → 100+n  (чтение)
--     edit   → 200+n  (изменение)
--     manage → 300+n  (управление)
--
-- где n — номер права внутри своего модуля и уровня по алфавиту кода. Базы
-- разнесены на 100, а столько прав одного уровня в модуле не бывает, поэтому
-- столкновение невозможно в принципе, а не «исправлено на сегодня».
--
-- ПОБОЧНЫЙ ЭФФЕКТ, О КОТОРОМ НАДО ЗНАТЬ: порядок прав на экране изменится —
-- теперь он идёт ступенями «вход → просмотр → изменение → управление», то есть
-- совпадает со шкалой, которую экран и показывает. Права, доступы и подписи
-- не меняются: правится ТОЛЬКО поле порядка.
--
-- Сама 20260916120000 НЕ правится: она уже применена, и менять применённую
-- миграцию — значит расходиться с тем, что реально лежит в базе.
--
-- Идемпотентно: row_number по неизменным данным даёт тот же результат.
-- ═════════════════════════════════════════════════════════════════════

-- ── 1. Каталог ──────────────────────────────────────────────────────────────
WITH ordered AS (
  SELECT
    id,
    CASE
      WHEN privilege_code = 'access' THEN 0
      ELSE CASE level
             WHEN 'view'   THEN 100
             WHEN 'edit'   THEN 200
             WHEN 'manage' THEN 300
             ELSE 400          -- уровень не проставлен: в самый конец модуля
           END
           + row_number() OVER (
               PARTITION BY module, COALESCE(level, '~')
               ORDER BY privilege_code
             )::INT
    END AS ord
  FROM module_privileges
)
UPDATE module_privileges mp
   SET sort_order = o.ord
  FROM ordered o
 WHERE mp.id = o.id
   AND mp.sort_order IS DISTINCT FROM o.ord;

-- ── 2. Тот же порядок в раскладке дерева отображения ────────────────────────
-- Иначе право «прыгало» бы внутри своего узла независимо от каталога.
UPDATE security_tree_items i
   SET sort_order = mp.sort_order
  FROM module_privileges mp
 WHERE mp.module = i.module
   AND mp.privilege_code = i.privilege_code
   AND i.sort_order IS DISTINCT FROM mp.sort_order;

-- ── 3. Самопроверка ─────────────────────────────────────────────────────────
-- Не EXCEPTION: если правило вдруг не покрыло какой-то случай, назвать его
-- вслух полезнее, чем заблокировать починку остальных.
DO $$
DECLARE
  dupes INT;
  sample TEXT;
BEGIN
  SELECT count(*), string_agg(module || ' @ ' || sort_order, ', ')
    INTO dupes, sample
    FROM (
      SELECT module, sort_order
        FROM module_privileges
       GROUP BY module, sort_order
      HAVING count(*) > 1
    ) t;

  IF dupes > 0 THEN
    RAISE WARNING 'Осталось пар (модуль, sort_order) с дублем: % — %', dupes, sample;
  ELSE
    RAISE NOTICE 'Порядок прав в каталоге однозначен: столкновений нет';
  END IF;
END $$;
