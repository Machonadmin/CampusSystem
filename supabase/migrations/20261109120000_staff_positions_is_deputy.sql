-- Посадка «סגן» (заместитель главы единицы).
--
-- Решение владельца 2026-11-09: права «Учёбы» вытекают из места человека в
-- оргструктуре (lib/permissions/structure-rules.ts). У главы (is_head) и
-- заместителя (is_deputy) — один и тот же набор прав в его единице и во всём,
-- что ниже неё; раздавать права команде может только глава.
--
-- Колонка необязательна для кода: до применения миграции заместителей просто
-- нет, всё остальное работает.
--
-- Идемпотентно. Применять ВРУЧНУЮ через Supabase Dashboard SQL Editor.
-- ═════════════════════════════════════════════════════════════════════

ALTER TABLE staff_positions
  ADD COLUMN IF NOT EXISTS is_deputy boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN staff_positions.is_deputy IS
  'סגן/ית — заместитель главы единицы: те же права «Учёбы», что у главы, без раздачи прав команде.';
