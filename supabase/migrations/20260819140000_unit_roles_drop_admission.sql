-- ============================================================================
-- Управляющие юнитами видят только СВОЁ: их учёбу, их студенток, их людей —
-- не центральный приём (קבלה). Владелец: «מנהל יחידה אמור לראות את מה ששייך
-- אליו — לימודים שלו, תלמידים שלו... לא קבלה».
--
-- Роли unit_manager и unit_secretary были засеяны с 'view_applicants'
-- (20260818190000), из-за чего в сайдбаре у них показывался раздел «קבלה»
-- (tab-access: committee = view_applicants). Убираем это право у обеих ролей.
-- Раздел «לимудим» (view_students) не затрагивается. Идемпотентно.
-- ============================================================================

DELETE FROM role_privileges
WHERE role_id IN (SELECT id FROM roles WHERE code IN ('unit_manager', 'unit_secretary'))
  AND privilege_code = 'view_applicants';
