-- ЛИЧНЫЕ НАСТРОЙКИ ИНТЕРФЕЙСА СОТРУДНИКА (решение владельца, 2026-09-23:
-- «каждый сотрудник сам настраивает, что он видит и где, в рамках своих прав»).
--
-- Одна строка на человека. В prefs (JSONB) лежит только РАСКЛАДКА экрана:
-- избранные пункты меню, скрытые пункты, порядок и видимость блоков главной.
-- ПРАВ здесь НЕТ и быть не может: сервер по-прежнему решает, что человеку
-- доступно (role_privileges / person_privileges). Настройка может только
-- СКРЫТЬ или ПЕРЕСТАВИТЬ то, что уже доступно, — «добавить» себе модуль нельзя.
--
-- Раньше тема и закреплённость меню жили только в браузере (localStorage), и
-- на телефоне сотрудник видел не то, что настроил на компьютере. Теперь
-- раскладка хранится на сервере и одинакова на всех устройствах.
--
-- Код развёрнут так, что работает и ДО этой миграции (настройки по умолчанию,
-- сохранение отвечает «функция ещё не включена»), и ПОСЛЕ неё.
--
-- Идемпотентно. Применять ВРУЧНУЮ в Supabase SQL Editor.
-- ═══════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS user_preferences (
  person_id  UUID PRIMARY KEY REFERENCES persons(id) ON DELETE CASCADE,
  prefs      JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE user_preferences IS
  'Личная раскладка интерфейса сотрудника (избранное, скрытые пункты меню, блоки главной). Не содержит прав: только скрывает/переставляет уже доступное.';

-- RLS: как на всех таблицах public (миграция 20260908120000). Приложение ходит
-- в Supabase только с сервера под service_role, который RLS обходит; для
-- anon/authenticated доступ закрыт полностью. Политик НЕ добавляем намеренно.
ALTER TABLE user_preferences ENABLE ROW LEVEL SECURITY;
