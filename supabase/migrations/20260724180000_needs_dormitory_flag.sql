-- ═════════════════════════════════════════════════════════════════════
-- Флаг «צריכה פנימייה» (needs_dormitory) на профиле journey.
-- Stage восстановления структуры приёма под бизнес-процесс v2:
--   этап «Пансион» (3 последовательных интервью — заведующая → психолог →
--   врач) активируется ТОЛЬКО если у абитуриентки установлен этот флаг.
--   По документу флаг гибкий: ставится при создании лида, в начале приёма
--   или во время проверки документов; при изменении — этап пансиона
--   активируется или пропускается.
--
-- Здесь только КОЛОНКА (аддитивно, deploy-safe). Условная активация
-- этапов и перестройка переходов — отдельными шагами (код + миграция),
-- каждый с проверкой на локальном Postgres до раскатки.
--
-- NULL = «ещё не решено» (по умолчанию не требует пансиона в логике активации).
-- Применять ВРУЧНУЮ через Supabase Dashboard SQL Editor.
-- ═════════════════════════════════════════════════════════════════════

ALTER TABLE education_journeys
  ADD COLUMN IF NOT EXISTS needs_dormitory boolean;

COMMENT ON COLUMN education_journeys.needs_dormitory IS
  'צריכה פנימייה: гейтит этап «Пансион» (3 интервью) в процессе приёма. '
  'NULL/false — этап пропускается; true — активируется. Ставится гибко на любом шаге.';
