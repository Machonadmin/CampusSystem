-- Отметка «входы до этого момента недействительны» для аккаунтов.
--
-- Контекст (аудит безопасности 2026-09-23): токен входа живёт 7 дней. Смена
-- или сброс пароля раньше не выводили человека с других устройств — старый
-- браузер или украденная кука продолжали работать до истечения токена.
--
-- sessions_valid_after: токены, выписанные раньше этой отметки, больше не
-- принимаются (lib/auth/live-session.ts). Отметку ставят смена пароля, первая
-- обязательная смена и сброс пароля администратором. NULL — ограничения нет
-- (текущие входы продолжают работать как раньше).
--
-- Код готов к любому порядку: до миграции он проверяет только, что аккаунт
-- активен, и не пишет в колонку. Идемпотентно. Применять ВРУЧНУЮ в Supabase
-- SQL Editor. Ожидаемый результат: "Success. No rows returned".
-- ============================================================================

ALTER TABLE public.person_accounts     ADD COLUMN IF NOT EXISTS sessions_valid_after timestamptz;
ALTER TABLE public.student_credentials ADD COLUMN IF NOT EXISTS sessions_valid_after timestamptz;
