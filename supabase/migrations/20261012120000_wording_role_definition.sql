-- «תואר משרה» → «הגדרת תפקיד» в текстах, которые живут в БД.
--
-- Решение владельца 2026-10-12: формулировку «תואר משרה / תוארי משרה» не
-- использовать нигде, вместо неё — «הגדרת תפקיד / הגדרות תפקיד». Подписи
-- интерфейса поменяны в messages/he.json; здесь — то, что экран «אבטחת מידע»
-- читает из БД: подписи и объяснения прав (module_privileges) и узлы дерева
-- отображения (security_tree_nodes). Пример: объяснение staff.access
-- «… מבנה ארגוני, עובדים ותוארי משרה.»
--
-- Меняются только эти четыре сочетания, остальной текст не трогается
-- (например, «תואר» в смысле учёной степени). Идемпотентно: после первого
-- прогона совпадений больше нет.
--
-- Применять ВРУЧНУЮ через Supabase Dashboard SQL Editor.
-- ═════════════════════════════════════════════════════════════════════

UPDATE module_privileges SET
  name_he = replace(replace(replace(replace(name_he,
    'תוארי המשרה', 'הגדרות התפקיד'),
    'תוארי משרה',  'הגדרות תפקיד'),
    'תואר המשרה',  'הגדרת התפקיד'),
    'תואר משרה',   'הגדרת תפקיד'),
  description_he = replace(replace(replace(replace(description_he,
    'תוארי המשרה', 'הגדרות התפקיד'),
    'תוארי משרה',  'הגדרות תפקיד'),
    'תואר המשרה',  'הגדרת התפקיד'),
    'תואר משרה',   'הגדרת תפקיד')
WHERE name_he LIKE '%תואר%משרה%' OR description_he LIKE '%תואר%משרה%';

UPDATE security_tree_nodes SET
  name_he = replace(replace(replace(replace(name_he,
    'תוארי המשרה', 'הגדרות התפקיד'),
    'תוארי משרה',  'הגדרות תפקיד'),
    'תואר המשרה',  'הגדרת התפקיד'),
    'תואר משרה',   'הגדרת תפקיד'),
  description_he = replace(replace(replace(replace(description_he,
    'תוארי המשרה', 'הגדרות התפקיד'),
    'תוארי משרה',  'הגדרות תפקיד'),
    'תואר המשרה',  'הגדרת התפקיד'),
    'תואר משרה',   'הגדרת תפקיד')
WHERE name_he LIKE '%תואר%משרה%' OR description_he LIKE '%תואר%משרה%';
