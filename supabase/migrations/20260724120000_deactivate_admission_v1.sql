-- Деактивация устаревшего шаблона «Приём» (admission, v1).
--
-- Контекст: приём абитуриент→студент давно ведётся многоэтапным процессом
-- 'acceptance' («Приёмная комиссия», 20260713170000). Автозапуск в коде уже
-- переключён на 'acceptance' (app/api/workflow/stages/[…]/complete/route.ts,
-- processes/[…]/close-early/route.ts). Одноэтапный 'admission' (v1) больше не
-- стартует, но остаётся видимым как активный шаблон в CRUD-списках.
--
-- Здесь просто снимаем флаг is_active. СТРОКУ НЕ УДАЛЯЕМ — на неё могут
-- ссылаться уже запущенные/исторические process_instances. Идемпотентно.
--
-- Применять ВРУЧНУЮ через Supabase Dashboard SQL Editor.
-- ═════════════════════════════════════════════════════════════════════

UPDATE process_templates
  SET is_active = false
  WHERE code = 'admission' AND is_active IS DISTINCT FROM false;
