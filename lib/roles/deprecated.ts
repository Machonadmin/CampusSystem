/**
 * Legacy-роли (модель «университета»), которые заменены на «модель рензе»
 * (מודל רזה) владельца:
 *   • управляющие места (главы юнитов/замы/деканы/…) = ОДНА роль unit_manager;
 *   • секретариат = unit_secretary; преподаватель = teacher; учащиеся = student/pupil.
 *   • Конкретное «кто именно» (רקטור / דיקן / ראש מחלקה …) — это ЯРЛЫК-должность
 *     (reference_positions), НЕ роль-право.
 *
 * Эти коды миграция 20260818190000 явно пометила как legacy и оставила в БД,
 * чтобы не ломать уже назначенных. Здесь мы прячем их из ПИКЕРОВ назначения и
 * из списка экрана «תפקידים והרשאות», НО НЕ удаляем: существующие назначения
 * продолжают работать. Чтобы вернуть роль в интерфейс — убрать её код отсюда.
 */
export const DEPRECATED_ROLE_CODES: ReadonlySet<string> = new Set([
  'rector',          // רקטור
  'dean',            // דיקן
  'school_director', // מנהל (מוסד)
  'vice_director',   // סגן מנהל
  'dept_head',       // ראש מחלקה
  'program_head',    // ראש תוכנית
  'curator',         // מחנך
])

export function isDeprecatedRole(code: string): boolean {
  return DEPRECATED_ROLE_CODES.has(code)
}
