// ─── Загрузка документа из браузера: общие помощники форм ───────────────────
//
// Три формы грузят файл multipart-запросом на наш API: «מסמכים» (карточка
// студентки), вкладка документов лида и «בירור יהדות». Здесь — то, что у них
// общее и что раньше ломало загрузку (жалоба клиента 2026-10-28: «בוחרים קובץ,
// וכפתור להעלות לא עובד»).

/**
 * Реальный предел тела запроса. Vercel отрезает запрос к функции больше ~4.5 МБ
 * ответом 413 FUNCTION_PAYLOAD_TOO_LARGE ещё ДО нашего кода (проверено на живом
 * сайте 2026-10-28: 1 МБ доходит до API, 5.2 МБ — 413). Поэтому прежние
 * 15 МБ (MAX_UPLOAD_BYTES) через этот путь недостижимы. Берём 4 МБ с запасом
 * на остальные поля формы. Владелец (2026-10-28) выбрал оставить предел 4 МБ
 * (подсказка в форме — «עד 4MB»), а не делать прямую загрузку в хранилище.
 */
export const REQUEST_UPLOAD_LIMIT_BYTES = 4 * 1024 * 1024

/** Файл не пролезет через запрос к API (см. REQUEST_UPLOAD_LIMIT_BYTES). */
export function exceedsRequestLimit(file: { size: number }): boolean {
  return file.size > REQUEST_UPLOAD_LIMIT_BYTES
}

/**
 * Название документа по имени файла: без пути и расширения. Подставляется,
 * когда поле названия пустое, — иначе кнопка «העלאה» оставалась серой
 * (в «בירור יהדות») или форма отвечала ошибкой «нужен заголовок».
 */
export function titleFromFileName(name: string): string {
  const base = name.split(/[\\/]/).pop() ?? ''
  const noExt = base.replace(/\.[^.]+$/, '')
  return (noExt || base).trim()
}
